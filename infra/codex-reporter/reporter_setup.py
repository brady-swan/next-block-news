def provision():
    values={'NBN_REPORTER_TOKEN':connection('reporter')['token'],
            'NBN_REPORTER_CONTROL_TOKEN':connection('supervisor')['token'],
            'NBN_REPORTER_API_ENABLED':'true','NBN_OPERATING_MODE':'infrastructure',
            'NBN_AUTOPOST_ENABLED':'false'}
    for key,value in values.items():
        # stdin keeps credentials out of argv and command output; never print values.
        r=subprocess.run(['railway','variables','set','--service',SERVICE,'--environment',ENVIRONMENT,
                          '--skip-deploys','--stdin',key],input=value,text=True,capture_output=True,cwd=REPO)
        if r.returncode: raise RuntimeError('Railway variable update failed for '+key)
    print(json.dumps({'configured_names':list(values),'deployment_triggered':False}))


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('action',choices=['prepare','provision'])
    globals()[p.parse_args().action]()
